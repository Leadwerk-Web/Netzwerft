class Leadwerk_Migration_Status_Controller {

	public static function status( $params = array() ) {
		leadwerk_migration_setup_environment();

		// Set params
		if ( empty( $params ) ) {
			$params = stripslashes_deep( array_merge( $_GET, $_POST ) );
		}

		// Set secret key
		$secret_key = null;
		if ( isset( $params['secret_key'] ) ) {
			$secret_key = trim( $params['secret_key'] );
		}

		// This endpoint is intentionally available to async browser loopbacks, but
		// it accepts only the read-only status credential, never an operation key.
		if ( ! Leadwerk_Migration_Security::verify_scoped_secret( $secret_key, 'status' ) ) {
			status_header( 403 );
			exit;
		}

		$job_id = isset( $params['storage'] ) && is_string( $params['storage'] ) ? trim( $params['storage'] ) : '';
		if ( ! preg_match( '/\A[A-Za-z0-9_-]{8,64}\z/D', $job_id ) ) {
			status_header( 400 );
			leadwerk_migration_json_response( array( 'errors' => array( __( 'A valid migration job identifier is required.', 'leadwerk-migration' ) ) ) );
			exit;
		}

		leadwerk_migration_json_response( get_option( 'leadwerk_migration_status_' . $job_id, array() ) );
		exit;
	}
}
