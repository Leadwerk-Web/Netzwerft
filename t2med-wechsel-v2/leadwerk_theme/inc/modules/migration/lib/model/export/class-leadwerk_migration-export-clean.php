class Leadwerk_Migration_Export_Clean {

	public static function execute( $params ) {

		// Delete storage files. The leadwerk_migration_status_<job_id> option lingers so poll
		// clients still see the terminal state; the daily cron sweeps it later.
		Leadwerk_Migration_Directory::delete( leadwerk_migration_storage_path( $params ) );

		if ( isset( $params['leadwerk_migration_export_cancel'] ) ) {
			do_action( 'leadwerk_migration_status_export_canceled', $params );
		}

		// Exit in console
		if ( defined( 'WP_CLI' ) || ! empty( $params['leadwerk_migration_inline'] ) ) {
			return $params;
		}

		exit;
	}
}
