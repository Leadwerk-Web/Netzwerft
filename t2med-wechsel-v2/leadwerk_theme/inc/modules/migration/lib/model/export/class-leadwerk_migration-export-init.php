class Leadwerk_Migration_Export_Init {

	public static function execute( $params ) {
		$blog_id = null;

		// Get subsite Blog ID
		if ( isset( $params['options']['sites'] ) && ( $sites = $params['options']['sites'] ) ) {
			if ( count( $sites ) === 1 ) {
				$blog_id = array_shift( $sites );
			}
		}

		do_action( 'leadwerk_migration_status_export_init', $params );

		// Set progress
		Leadwerk_Migration_Status::info( __( 'Preparing to export...', 'leadwerk-migration' ) );

		// Set archive
		if ( empty( $params['archive'] ) ) {
			$params['archive'] = leadwerk_migration_archive_file( $blog_id );
		}

		// Set storage
		if ( empty( $params['storage'] ) ) {
			$params['storage'] = leadwerk_migration_storage_folder();
		}

		return $params;
	}
}
